const tbody = document.getElementById('returnRows');
const originalValues = new Map();
rows.forEach((row, index) => {
  const tr = document.createElement('tr');
  if (index === 0 || [10, 24, 38].includes(index)) tr.classList.add('group-start');
  const cells = row.map((value, cellIndex) => {
    if (cellIndex === 0) return `<td>${value}</td>`;
    if (cellIndex === 1) return `<td>${value}</td>`;
    if (cellIndex === 2) return `<td>${value}</td>`;
    if (value === '——') return `<td class="dash">——</td>`;
    const key = `${index}-${cellIndex}`;
    originalValues.set(key, value);
    return `<td><input inputmode="decimal" aria-label="第${row[2]}栏 ${cellIndex < 5 ? '一般项目' : '即征即退'}${cellIndex % 2 === 0 ? '本月数' : '本年累计'}" value="${value}" data-key="${key}" /></td>`;
  }).join('');
  tr.innerHTML = cells;
  tbody.appendChild(tr);
});

function formatAmount(input) {
  const raw = input.value.replace(/,/g, '').trim();
  if (!raw || raw === '-') return;
  const numeric = Number(raw);
  if (Number.isNaN(numeric)) return;
  input.value = numeric.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

document.querySelectorAll('.return-table input').forEach(input => {
  input.addEventListener('blur', () => formatAmount(input));
});
